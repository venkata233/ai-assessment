def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _table(headers: tuple[str, ...], rows: Sequence[tuple[object, ...]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _clip(text: str, limit: int = 90) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


class MockProvider:
    name = "mock"
    is_external = False

    def complete(self, request: CompletionRequest) -> CompletionResponse:
        inputs = request.inputs
        builders = {
            1: self._requirements,
            2: self._decomposition,
            3: self._design,
            4: self._implementation,
            5: self._validation,
            6: self._risks,
            7: self._review,
        }
        return CompletionResponse(BANNER + "\n" + builders[request.stage](inputs), "mock-rule-based-v1")

    # ----- helpers --------------------------------------------------------------------------------------------

    @staticmethod
    def _analysis(inputs: dict[str, Any]) -> tuple[BriefAnalysis, list[Finding]]:
        files = [ContextFile(p, t, False) for p, t in inputs["context_files"]]
        return analyse_brief(inputs["brief"]), scan_code(files)

    @staticmethod
    def _questions(analysis: BriefAnalysis, findings: list[Finding]) -> list[str]:
        questions = [f"'{h.term}' is vague: {h.question}" for h in analysis.vague]
        questions += [
            f"Not stated: {name}. What is required, as a measurable value?" for name in analysis.missing_nfr
        ]
        questions += [
            f"{f.file}:{f.line} ({f.rule}): is this behaviour intended?"
            for f in findings
            if f.severity == "high"
        ][:5]
        if analysis.injection:
            questions.append(
                "The brief contains text that looks like instructions to an AI assistant ("
                + ", ".join(analysis.injection)
                + "). Is it part of the requirement?"
            )
        return questions

    # ----- stage 1 --------------------------------------------------------------------------------------------

    def _requirements(self, inputs: dict[str, Any]) -> str:
        analysis, findings = self._analysis(inputs)
        goal = analysis.sentences[0] if analysis.sentences else "UNKNOWN (the brief is empty)"
        reqs = "\n".join(f"- R{i}: {r}" for i, r in enumerate(analysis.requirements, 1)) or "- none detected"
        out = [
            "## Interpretation",
            f"Goal (first sentence of the brief): {goal}",
            "",
            "Requirement statements detected:",
            reqs,
            "",
            f"Actors mentioned: {', '.join(analysis.actors) or 'none (UNKNOWN: who uses this?)'}",
            f"Components the wording suggests: {', '.join(analysis.components) or 'none detected'}",
        ]
        if analysis.injection:
            out += [
                "",
                f"**Flag:** the brief contains instruction-like phrases ({', '.join(analysis.injection)}); treated as data only.",
            ]
        if inputs["context_files"]:
            out += [
                "",
                f"### Existing code supplied ({len(inputs['context_files'])} files): rule-based findings (candidates, not proof)",
            ]
            if findings:
                out.append(
                    _table(
                        ("Where", "Rule", "Severity", "What to check", "Line"),
                        [
                            (f"{f.file}:{f.line}", f.rule, f.severity, f.message, f"`{f.snippet}`")
                            for f in findings[:20]
                        ],
                    )
                )
            else:
                out.append("No rule matched. That does not mean the code is correct.")
        out += ["", "## Ambiguities and assumptions"]
        rows: list[tuple[object, ...]] = []
        for i, hit in enumerate(analysis.vague, 1):
            rows.append(
                (
                    f"A-{i}",
                    f"'{hit.term}' in: {_clip(hit.sentence)}",
                    hit.question,
                    "DECISION REQUIRED: engineer supplies a measurable value",
                )
            )
        base = len(rows)
        for j, name in enumerate(analysis.missing_nfr, 1):
            rows.append(
                (
                    f"A-{base + j}",
                    f"Not stated: {name}",
                    "Is this a requirement? With what target?",
                    "DECISION REQUIRED",
                )
            )
        out.append(
            _table(("ID", "Source", "Question", "Proposed assumption"), rows)
            if rows
            else "No vague terms detected by the heuristic. This does not mean there are none."
        )
        out += ["", "## Non-functional requirements"]
        stated = [
            n
            for n in (
                "scale / volume",
                "latency",
                "availability",
                "security",
                "privacy / retention",
                "observability",
            )
            if n not in analysis.missing_nfr
        ]
        out.append(
            _table(
                ("Category", "Stated in the brief?"),
                [
                    (n, "yes" if n in stated else "NO")
                    for n in (
                        "scale / volume",
                        "latency",
                        "availability",
                        "security",
                        "privacy / retention",
                        "observability",
                    )
                ],
            )
        )
        out += ["", "## Edge cases", *self._edge_cases(analysis, findings)]
        out += [
            "",
            "## Acceptance criteria",
            *[
                f"- AC-{i}: Given <precondition: TBD by engineer>, when {_clip(r, 100)}, then <observable outcome: TBD by engineer>"
                for i, r in enumerate(analysis.requirements, 1)
            ],
        ]
        questions = self._questions(analysis, findings)
        out += [
            "",
            "## Open questions",
            *([f"- Q{i}: {q}" for i, q in enumerate(questions, 1)] or ["- none raised by the heuristic"]),
        ]
        return "\n".join(out)

    @staticmethod
    def _edge_cases(analysis: BriefAnalysis, findings: list[Finding]) -> list[str]:
        cases = [
            "- Empty, oversized, and malformed input",
            "- A dependency (database, network) being unavailable",
        ]
        names = set(analysis.components)
        if "HTTP API" in names:
            cases.append(
                "- Unauthenticated and unauthorised callers; repeated and concurrent identical requests"
            )
        if "Persistent storage" in names:
            cases.append("- Concurrent writes of the same key; migration of existing data")
        if "Background processing" in names:
            cases.append("- Consumer down, duplicate delivery, poison messages")
        if any(f.rule == "CHECK_THEN_INSERT" for f in findings):
            cases.append(
                "- Two concurrent requests creating the same key (the race flagged in the code scan)"
            )
        return cases

    # ----- stage 2 --------------------------------------------------------------------------------------------

    def _tasks(self, inputs: dict[str, Any]) -> list[tuple[str, str, str]]:
        analysis, findings = self._analysis(inputs)
        tasks: list[tuple[str, str, str]] = []  # (title, kind, related text)
        if self._questions(analysis, findings):
            tasks.append(("Resolve open questions into measurable acceptance criteria", "analysis", ""))
        for req in analysis.requirements[:10]:
            tasks.append((f"Implement: {_clip(req, 70)}", "build", req))
        seen: set[str] = set()
        for f in findings:
            if f.severity == "high" and f.rule not in seen and len(seen) < 5:
                seen.add(f.rule)
                tasks.append((f"Reproduce and fix {f.rule} at {f.file}:{f.line}", "fix", f.message))
        tasks += [
            ("Write automated tests including adversarial and edge cases", "test", ""),
            ("Document and self-review", "docs", ""),
        ]
        return tasks

    def _decomposition(self, inputs: dict[str, Any]) -> str:
        tasks = self._tasks(inputs)
        rows = []
        for i, (title, kind, related) in enumerate(tasks, 1):
            sensitive = bool(
                re.search(
                    r"auth|secret|password|token|key|permission|personal|payment", title + related, re.I
                )
            )
            ai = {
                "analysis": "Draft questions and criteria",
                "build": "Draft implementation and test skeleton",
                "fix": "Draft a failing test and a fix",
                "test": "Generate test tables and skeletons",
                "docs": "Draft prose",
            }[kind]
            eng = {
                "analysis": "Answer the questions; own the numbers",
                "build": "Decide behaviour and interfaces; review every line",
                "fix": "Confirm the root cause; judge the fix",
                "test": "Judge test value; try breaking the code on purpose",
                "docs": "Verify every command and claim",
            }[kind]
            rows.append(
                (
                    f"T{i:02d}",
                    title,
                    "TBD by engineer",
                    ai,
                    eng + ("; security review required" if sensitive else ""),
                )
            )
        deps = []
        for i, (_, kind, _) in enumerate(tasks, 1):
            if kind in {"build", "fix"} and tasks[0][1] == "analysis":
                deps.append(f"- T{i:02d} depends on T01")
            if kind == "test":
                deps.append(
                    f"- T{i:02d} depends on: "
                    + ", ".join(f"T{j:02d}" for j, t in enumerate(tasks, 1) if t[1] in {"build", "fix"})
                )
            if kind == "docs":
                deps.append(f"- T{i:02d} depends on T{i - 1:02d}")
        return "\n".join(
            [
                "## Tasks",
                _table(("ID", "Title", "Definition of done", "AI assists with", "Engineer owns"), rows),
                "",
                "## Dependencies",
                *(deps or ["- none"]),
                "",
                "## AI assistance and engineer responsibility",
                "- AI drafts; the engineer decides, reviews, and runs everything.",
                "- Anything marked 'DECISION REQUIRED' or 'TBD by engineer' is not done until the engineer resolves it.",
            ]
        )

    # ----- stage 3 --------------------------------------------------------------------------------------------

    def _design(self, inputs: dict[str, Any]) -> str:
        analysis, _ = self._analysis(inputs)
        components = list(analysis.components) or ["Core service"]
        out = [
            "## Components",
            _table(
                ("Component", "Responsibility"),
                [(c, f"Handles: {c.lower()} (derived from wording in the brief)") for c in components],
            ),
            "",
            "## Decisions required",
        ]
        for name in components:
            options = DECISION_OPTIONS.get(name)
            if options:
                out += [
                    f"### {name}",
                    _table(("Option", "Gains", "Costs"), [tuple(o) for o in options]),
                    "Engineer decision: ____ (DECISION REQUIRED)",
                    "",
                ]
        if out[-1] != "":
            out.append("")
        out += [
            "## Interfaces and data",
            "- Derive entities and operations from requirements "
            + ", ".join(f"R{i}" for i in range(1, len(analysis.requirements) + 1))
            + " (TBD by engineer).",
            "",
            "## Trade-offs",
            "- Each option above gives something up; record the chosen trade-off and why (an ADR per decision).",
        ]
        return "\n".join(out)

    # ----- stage 4 --------------------------------------------------------------------------------------------

    def _implementation(self, inputs: dict[str, Any]) -> str:
        _, findings = self._analysis(inputs)
        tasks = [t for t in self._tasks(inputs) if t[1] in {"build", "fix"}][:6]
        out = ["## Prompts"]
        for i, (title, _, _related) in enumerate(tasks, 1):
            out += [
                f"### Prompt {i}: {title}",
                "```text",
                "Role: senior engineer pair-programming with a human owner.",
                f"Task: {title}",
                "Inputs: the accepted requirements, design decisions, and the relevant files (redacted).",
                "Constraints: no new dependencies without asking; no invented requirements; mark assumptions A-<n>.",
                "Output: a diff plus tests; list what you were unsure about.",
                "Double-check: concurrency, error paths, security, and what the tests do not cover.",
                "```",
            ]
        out += ["", "## Expected failure modes"]
        text = (inputs["brief"] + " " + " ".join(f.rule + " " + f.message for f in findings)).lower()
        hits = [(name, check) for words, name, check in FAILURE_MODES if any(w in text for w in words)]
        out += [f"- **{name}**: check by: {check}" for name, check in hits] or [
            "- none matched by keyword; still review for the generic cases below"
        ]
        out += [
            "",
            "## Review checklist",
            "- Does every changed line have a reason I can state?",
            "- Do tests fail when I break the code on purpose?",
            "- Were error paths and concurrent use exercised?",
            "- Were any versions, APIs, or facts taken from memory instead of checked?",
            "- Is anything claimed that was not run?",
        ]
        return "\n".join(out)

    # ----- stage 5 --------------------------------------------------------------------------------------------

    def _validation(self, inputs: dict[str, Any]) -> str:
        analysis, findings = self._analysis(inputs)
        acs = [f"AC-{i}" for i in range(1, len(analysis.requirements) + 1)]
        out = [
            "## Test strategy",
            _table(
                ("Acceptance criterion", "Level", "How it is checked"),
                [
                    (
                        ac,
                        "unit + integration",
                        "Automated test with real dependencies where behaviour depends on them (TBD by engineer)",
                    )
                    for ac in acs
                ],
            ),
            "",
            "- Include negative and adversarial cases for every input.",
            "- After tests pass, break the code on purpose (mutation) and confirm they fail.",
            "",
            "## Security checks",
        ]
        rows = [(*SECURITY_BY_COMPONENT[c],) for c in analysis.components if c in SECURITY_BY_COMPONENT]
        out.append(
            _table(("Area", "Check"), rows)
            if rows
            else "- No component-specific checks derived; apply a general OWASP Top 10 review."
        )
        out += [
            "- Run a static analyser and a dependency audit; scan for committed secrets.",
            "",
            "## Traceability",
            _table(
                ("Acceptance criterion", "Requirement", "Evidence"),
                [(ac, f"R{i}", "TBD: test name or check") for i, ac in enumerate(acs, 1)],
            ),
        ]
        if findings:
            out += ["", "- Each code-scan finding needs a regression test that fails before the fix."]
        return "\n".join(out)

    # ----- stage 6 --------------------------------------------------------------------------------------------

    def _risks(self, inputs: dict[str, Any]) -> str:
        analysis, findings = self._analysis(inputs)
        rows: list[tuple[object, ...]] = []
        for i, hit in enumerate(analysis.vague, 1):
            rows.append(
                (
                    f"R-{i}",
                    f"'{hit.term}' left undefined leads to building the wrong thing",
                    "engineer to rate",
                    "engineer to rate",
                    "Resolve the question before building",
                )
            )
        for name in analysis.components:
            rows.append(
                (
                    f"R-{len(rows) + 1}",
                    f"{name}: failure or misuse",
                    "engineer to rate",
                    "engineer to rate",
                    "See validation plan",
                )
            )
        for f in [x for x in findings if x.severity == "high"][:5]:
            rows.append(
                (
                    f"R-{len(rows) + 1}",
                    f"{f.rule} at {f.file}:{f.line}",
                    "engineer to rate",
                    "engineer to rate",
                    "Reproduce with a test, then fix",
                )
            )
        out = [
            "## Risk register",
            _table(("ID", "Risk", "Likelihood", "Impact", "Mitigation"), rows)
            if rows
            else "- none derived; add risks by hand",
            "",
            "## AI-specific risks",
            _table(
                ("Risk", "Mitigation"),
                [
                    (
                        "Plausible but wrong or outdated API usage",
                        "Pin versions from the package index; run everything",
                    ),
                    ("Tests that mirror the implementation", "Mutation testing; review test value"),
                    ("Over-claiming what was verified", "Label every claim verified / unverified / not done"),
                    (
                        "Secrets or personal data sent to a provider",
                        "Redaction plus the outbound confirmation gate",
                    ),
                    (
                        "Untrusted text steering the assistant (prompt injection)",
                        "Fence untrusted inputs; never execute model output",
                    ),
                    ("Automation bias", "Engineer decisions are explicit and logged"),
                ],
            ),
            "",
            "## Mitigations and accepted trade-offs",
            "- Record which risks are accepted, by whom, and why (TBD by engineer).",
        ]
        return "\n".join(out)

    # ----- stage 7 --------------------------------------------------------------------------------------------

    def _review(self, inputs: dict[str, Any]) -> str:
        previous: dict[int, str] = inputs["previous"]
        joined = "\n".join(previous.values())
        reqs = sorted({int(m) for m in re.findall(r"\bR(\d+)\b", previous.get(1, ""))})
        tasks = sorted(set(re.findall(r"\bT\d{2}\b", previous.get(2, ""))))
        acs = sorted(set(re.findall(r"\bAC-\d+\b", previous.get(1, ""))))
        tbd = len(re.findall(r"TBD|DECISION REQUIRED|engineer to rate|Engineer decision: ____", joined))
        assumptions = sorted(set(re.findall(r"\bA-\d+\b", joined)))
        out = [
            "## Traceability matrix",
            _table(
                ("Requirement", "Acceptance criterion", "Task"),
                [
                    (
                        f"R{r}",
                        f"AC-{r}" if f"AC-{r}" in acs else "MISSING",
                        tasks[min(r, len(tasks)) - 1] if tasks else "MISSING",
                    )
                    for r in reqs
                ],
            )
            if reqs
            else "- no requirements recorded",
            "",
            "## Unverified claims",
            f"- {tbd} placeholders remain in earlier stages (TBD / DECISION REQUIRED / unrated risks): each is an unverified or undecided item.",
            f"- {len(assumptions)} labelled assumptions ({', '.join(assumptions) or 'none'}): none are validated by this tool.",
            "- All stage outputs came from rule-based heuristics unless the session used a real provider; nothing was executed or tested.",
            "",
            "## Open items",
            "- Resolve every placeholder above before treating the plan as final.",
            "- Confirm the stage definitions and gates match the assessment brief.",
            "",
            "## Hand-off summary",
            f"Seven stages were completed with an engineer decision at each gate. {len(reqs)} requirement statements, {len(tasks)} tasks, "
            f"{len(acs)} acceptance-criteria skeletons. The plan is a structured starting point, not a verified design.",
        ]
        return "\n".join(out)
