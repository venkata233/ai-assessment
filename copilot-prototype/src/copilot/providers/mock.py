"""Offline, deterministic provider. **Not an AI model**: rule-based heuristics over the brief and any supplied code.

Purpose: let the whole workflow (stages, gates, redaction, audit, UI) run with no network, no key, and reproducible output.
What it produces is a structured *starting point with questions*; it never makes decisions (those are written as
"DECISION REQUIRED") and it never invents numbers. Every output carries a banner saying so.
"""

